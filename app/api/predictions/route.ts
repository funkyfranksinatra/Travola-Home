// app/api/predictions/route.ts — the AI's week ahead, read-only.
//
// Travola Home does NOT generate forecasts; Travola-OS owns that job and
// its research budget. This reads the published cache so an owner can see
// the week without opening the floor app — and scores the days already
// past against what actually happened, which is the part that earns trust
// in the number for next week.
import { prisma } from "@/lib/prisma";
import { withTenant } from "@/lib/tenant";
import { loadForecastAccuracy } from "@/lib/analytics/queries";
import { addDays, serviceDateOf } from "@/lib/analytics/math";

export const dynamic = "force-dynamic";

export async function GET(request: Request) {
  return withTenant(request, async (restaurantId) => {
    const today = new Date().toISOString().slice(0, 10);
    const horizon = new Date(Date.now() + 13 * 86_400_000).toISOString().slice(0, 10);

    const rows = await prisma.shiftForecast.findMany({
      where: { restaurantId, date: { gte: today, lte: horizon } },
      orderBy: [{ date: "asc" }, { createdAt: "desc" }],
    });

    // One row per date: the most recently written revision wins.
    const byDate = new Map<string, (typeof rows)[number]>();
    for (const row of rows) if (!byDate.has(row.date)) byDate.set(row.date, row);

    const days = [...byDate.values()].map((row) => {
      const payload = (row.payload ?? {}) as Record<string, any>;
      return {
        date: row.date,
        source: row.source,
        generatedAt: payload.generatedAt ?? row.createdAt.toISOString(),
        closed: Boolean(payload.closed),
        research: Boolean(payload.research),
        covers: payload.covers ?? null,
        booked: payload.booked ?? null,
        walkIns: payload.walkIns ?? null,
        turn: payload.turn ?? null,
        staffing: payload.staffing ?? null,
        sections: Array.isArray(payload.sections) ? payload.sections : [],
        hourly: Array.isArray(payload.hourly) ? payload.hourly : [],
        lastTableOut: payload.lastTableOut ?? "",
        factors: payload.factors ?? null,
      };
    });

    const to = serviceDateOf(today);
    const accuracy = await loadForecastAccuracy(restaurantId, addDays(to, -60), to);

    return Response.json({
      days,
      accuracy: accuracy
        .filter((row) => row.predicted != null && row.actual != null)
        .map((row) => ({
          date: row.date,
          predicted: row.predicted,
          actual: row.actual,
          errorPct:
            row.actual && row.actual > 0
              ? Math.round((Math.abs((row.predicted as number) - row.actual) / row.actual) * 1000) / 10
              : null,
        })),
      note:
        days.length === 0
          ? "No forecast has been published for the days ahead. Forecasts are generated by the floor app's shift intelligence — open Travola-OS and run the week to fill this in."
          : null,
    });
  });
}
