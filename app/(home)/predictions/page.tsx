"use client";

// app/(home)/predictions/page.tsx — the AI's week, and its track record.
//
// Read-only: the floor app owns forecast generation and its research
// budget. What Travola Home adds is the part that makes a forecast worth
// acting on — how the last two months of predictions actually scored. A
// number with no history behind it is a guess in a nice font, so accuracy
// is placed ABOVE the week rather than buried under it.
//
// Predicted and actual are the same measure in the same unit, so they
// share one axis. Two y-scales here would be the classic dashboard lie.
import { useEffect, useState } from "react";
import { AreaChart, Columns, Empty, Ring, StatTile, VIZ } from "@/components/charts";
import { Card, Chip, PageHeader, SectionHeading } from "@/components/ui";
import { dateLabel, integer, minutes, percent, shortDate } from "@/lib/format";

type Day = {
  date: string; source: string; generatedAt: string; closed: boolean; research: boolean;
  covers: { expected?: number; low?: number; high?: number; confidence?: string } | null;
  booked: { covers?: number; parties?: number } | null;
  walkIns: { expected?: number; historicalSharePct?: number } | null;
  turn: { minutes?: number; source?: string } | null;
  staffing: Record<string, unknown> | null;
  sections: Array<{ zone?: string; expectedCovers?: number }>;
  hourly: Array<{ hour?: number; covers?: number }>;
  lastTableOut: string;
  factors: { used?: Array<{ label: string; detail: string; impactPct: number }> } | null;
};

type Payload = {
  days: Day[];
  accuracy: Array<{ date: string; predicted: number | null; actual: number | null; errorPct: number | null }>;
  note: string | null;
};

export default function PredictionsPage() {
  const [data, setData] = useState<Payload | null>(null);
  const [links, setLinks] = useState<{ floor: string; pantry: string }>({ floor: "", pantry: "" });
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    fetch("/api/predictions")
      .then(async (response) => {
        if (!response.ok) throw new Error((await response.json().catch(() => ({}))).error ?? "Could not load.");
        return response.json();
      })
      .then(setData)
      .catch((err) => setError(err.message));
    // Only needed for the empty state's call to action.
    fetch("/api/overview")
      .then((response) => (response.ok ? response.json() : null))
      .then((payload) => payload?.links && setLinks(payload.links))
      .catch(() => undefined);
  }, []);

  if (error) return <Empty>{error}</Empty>;
  if (!data) return <div className="card h-64 animate-pulse" />;

  const scored = data.accuracy.filter((row) => row.errorPct != null);
  const meanError = scored.length ? scored.reduce((sum, row) => sum + (row.errorPct as number), 0) / scored.length : null;
  const within10 = scored.length ? (scored.filter((row) => (row.errorPct as number) <= 10).length / scored.length) * 100 : null;

  // Oldest first for the chart; the API returns newest first.
  const timeline = [...scored].reverse();
  const weekTotal = data.days.reduce((sum, day) => sum + (day.covers?.expected ?? 0), 0);

  return (
    <div className="flex flex-col gap-7">
      <PageHeader
        eyebrow="Predictions"
        title="The week ahead"
        note="Generated by the floor app's shift intelligence. This is a read-only view — run or re-run a forecast from Travola-OS."
        right={
          weekTotal > 0 ? (
            <div className="text-right">
              <p className="label">Forecast covers, next {data.days.length} days</p>
              <p className="figure text-ink-50 mt-1.5">{integer(weekTotal)}</p>
            </div>
          ) : null
        }
      />

      {data.note ? (
        <Card className="p-8 text-center" lit>
          <p className="text-base text-ink-50">No forecast has been published for the days ahead.</p>
          <p className="text-sm text-ink-400 mt-2 max-w-lg mx-auto leading-relaxed">
            Forecasts come from the floor app&rsquo;s shift intelligence, which reads your booking history, the
            day of the week and — on Pro — weather and local events. Run the week there and it appears here.
          </p>
          {links.floor ? (
            <a
              href={links.floor}
              target="_blank"
              rel="noreferrer"
              className="inline-block mt-5 rounded-lg bg-ai px-4 py-2 text-sm font-semibold text-bg hover:opacity-90"
            >
              Open the floor manager ↗
            </a>
          ) : null}
        </Card>
      ) : null}

      {meanError != null ? (
        <section className="grid gap-5 lg:grid-cols-3 items-start">
          <Card className="p-5 flex items-center">
            <Ring
              pct={within10}
              label="Within 10% of actual"
              caption={`Across ${scored.length} completed service ${scored.length === 1 ? "day" : "days"} in the last two months.`}
              tone={VIZ[2]}
            />
          </Card>
          <StatTile
            label="Average forecast error"
            value={percent(meanError)}
            hint="Mean gap between predicted and actual covers. Lower is better."
            footnote={scored.length < 7 ? `Only ${scored.length} days scored so far.` : undefined}
          />
          <Card className="p-5">
            <SectionHeading title="Predicted against actual" />
            {timeline.length >= 2 ? (
              <AreaChart
                series={[
                  { name: "Predicted", points: timeline.map((r) => ({ key: r.date, label: shortDate(r.date), value: r.predicted })) },
                  { name: "Actual", points: timeline.map((r) => ({ key: r.date, label: shortDate(r.date), value: r.actual })) },
                ]}
                format={(value) => `${integer(value)} covers`}
                height={150}
              />
            ) : (
              <Empty>Not enough scored days yet to draw the comparison.</Empty>
            )}
          </Card>
        </section>
      ) : null}

      {data.days.length ? (
        <section className="flex flex-col gap-4">
          <SectionHeading title="Day by day" note="The band is the forecast — the midpoint alone would claim precision the model does not have." />
          <div className="grid gap-4 xl:grid-cols-2">
            {data.days.map((day) => <DayCard key={day.date} day={day} />)}
          </div>
        </section>
      ) : null}
    </div>
  );
}

function DayCard({ day }: { day: Day }) {
  const expected = day.covers?.expected ?? null;
  const low = day.covers?.low ?? null;
  const high = day.covers?.high ?? null;
  const span = low != null && high != null && high > low ? high - low : null;
  const position = span && expected != null ? ((expected - low!) / span) * 100 : 50;
  const hourly = (day.hourly ?? [])
    .filter((row) => typeof row.hour === "number")
    .map((row) => ({
      key: String(row.hour),
      label: (row.hour as number) === 12 ? "12p" : (row.hour as number) > 12 ? `${(row.hour as number) - 12}p` : `${row.hour}a`,
      value: Number(row.covers ?? 0),
    }));

  return (
    <Card className="p-5" lit>
      <div className="flex items-start justify-between gap-4 flex-wrap">
        <div className="min-w-0">
          <div className="flex items-center gap-2 flex-wrap">
            <span className="text-lg font-semibold text-ink-50 tracking-tight">{dateLabel(day.date)}</span>
            {day.closed ? <Chip>closed</Chip> : null}
            {day.research ? <Chip tone="accent">research applied</Chip> : null}
            {day.covers?.confidence ? <Chip>{day.covers.confidence} confidence</Chip> : null}
          </div>
          <p className="text-xs text-ink-400 mt-1.5">
            {day.booked?.covers != null ? `${integer(day.booked.covers)} covers already booked` : ""}
            {day.walkIns?.expected != null ? ` · ${integer(day.walkIns.expected)} walk-ins expected` : ""}
            {day.turn?.minutes != null ? ` · ${minutes(day.turn.minutes)} turn` : ""}
          </p>
        </div>
        <div className="text-right shrink-0">
          <span className="figure text-ink-50">{integer(expected)}</span>
          <p className="text-[11px] text-ink-400 mt-0.5">covers</p>
        </div>
      </div>

      {span ? (
        <div className="mt-4">
          <div className="relative h-2 rounded-full bg-panel-up overflow-hidden">
            <span className="absolute inset-0" style={{ background: "linear-gradient(90deg, var(--color-ai-muted), var(--color-ai-bg) 50%, var(--color-ai-muted))" }} />
            <span
              className="absolute top-1/2 w-3 h-3 rounded-full -translate-y-1/2 -translate-x-1/2"
              style={{ left: `${Math.max(5, Math.min(95, position))}%`, background: VIZ[0], boxShadow: "0 0 0 2px var(--color-panel-card)" }}
            />
          </div>
          <p className="flex justify-between text-[11px] text-ink-400 mt-1.5 tabular-nums">
            <span>{integer(low)}</span><span>likely range</span><span>{integer(high)}</span>
          </p>
        </div>
      ) : null}

      {hourly.length ? (
        <div className="mt-5">
          <p className="label mb-2">Expected by hour</p>
          <Columns points={hourly} format={(value) => integer(value)} height={90} />
        </div>
      ) : null}

      {day.sections.length ? (
        <div className="mt-4 flex flex-wrap gap-1.5">
          {day.sections.map((section, index) => (
            <Chip key={`${section.zone}-${index}`}>{section.zone}: {integer(section.expectedCovers ?? null)}</Chip>
          ))}
        </div>
      ) : null}

      {day.factors?.used?.length ? (
        <ul className="mt-4 flex flex-col gap-1">
          {day.factors.used.map((factor, index) => (
            <li key={index} className="text-xs text-ink-400">
              <span className="text-ink-200">{factor.label}</span>
              {factor.impactPct ? ` (${factor.impactPct > 0 ? "+" : ""}${factor.impactPct}%)` : ""} — {factor.detail}
            </li>
          ))}
        </ul>
      ) : null}

      {day.lastTableOut ? (
        <p className="text-xs text-ink-400 mt-3">Typical last table out: {day.lastTableOut}</p>
      ) : null}
    </Card>
  );
}
