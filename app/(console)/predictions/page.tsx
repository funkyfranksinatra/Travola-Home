"use client";

// app/(console)/predictions/page.tsx — the AI's week, and its track record.
//
// Read-only: the floor app owns forecast generation and its research
// budget. What the Console adds is the part that makes a forecast worth
// reading — how the last two months of predictions actually scored. A
// number with no history behind it is a guess with a nice font.
import { useEffect, useState } from "react";
import { BarChart, Card, Chip, Empty, SectionHeading } from "@/components/ui";
import { dateLabel, integer, minutes, percent } from "@/lib/format";

type Day = {
  date: string; source: string; generatedAt: string; closed: boolean; research: boolean;
  covers: { expected?: number; low?: number; high?: number; confidence?: string; method?: string } | null;
  booked: { covers?: number; parties?: number } | null;
  walkIns: { expected?: number; historicalSharePct?: number } | null;
  turn: { minutes?: number; source?: string } | null;
  staffing: Record<string, unknown> | null;
  sections: Array<{ zone?: string; expectedCovers?: number }>;
  hourly: Array<{ hour?: number; covers?: number }>;
  lastTableOut: string;
  factors: { used?: Array<{ label: string; detail: string; impactPct: number }>; excluded?: Array<{ label: string; reason: string }> } | null;
};

type Payload = {
  days: Day[];
  accuracy: Array<{ date: string; predicted: number | null; actual: number | null; errorPct: number | null }>;
  note: string | null;
};

export default function PredictionsPage() {
  const [data, setData] = useState<Payload | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    fetch("/api/predictions")
      .then(async (response) => {
        if (!response.ok) throw new Error((await response.json().catch(() => ({}))).error ?? "Could not load.");
        return response.json();
      })
      .then(setData)
      .catch((err) => setError(err.message));
  }, []);

  if (error) return <Empty>{error}</Empty>;
  if (!data) return <p className="text-sm text-ink-400">Loading…</p>;

  const scored = data.accuracy.filter((row) => row.errorPct != null);
  const meanError = scored.length
    ? scored.reduce((sum, row) => sum + (row.errorPct as number), 0) / scored.length
    : null;

  return (
    <div className="space-y-8">
      <header>
        <p className="tv-label">Predictions</p>
        <h1 className="tv-heading text-ink-50 mt-1" style={{ fontSize: "calc(var(--heading-size) * 1.3)" }}>
          The week ahead
        </h1>
        <p className="text-sm text-ink-400 mt-1">
          Generated by the floor app&rsquo;s shift intelligence. This is a read-only view — run or re-run a forecast
          from Travola-OS.
        </p>
      </header>

      {data.note ? <Card><p className="text-sm text-ink-200">{data.note}</p></Card> : null}

      {meanError != null ? (
        <Card>
          <SectionHeading
            title="How well it has been doing"
            note={`Scored against ${scored.length} completed service ${scored.length === 1 ? "day" : "days"} in the last two months.`}
          />
          <div className="flex items-baseline gap-3 flex-wrap">
            <span className="tv-metric text-ink-50">{percent(meanError)}</span>
            <span className="text-sm text-ink-400">average gap between predicted and actual covers</span>
          </div>
          <div className="mt-4">
            <BarChart
              points={scored.slice(0, 14).reverse().map((row) => ({
                key: row.date,
                label: dateLabel(row.date).slice(0, 6),
                value: row.errorPct ?? 0,
              }))}
              format={(value) => percent(value)}
              height={120}
            />
          </div>
        </Card>
      ) : null}

      {data.days.length === 0 ? null : (
        <section className="space-y-3">
          <SectionHeading title="Day by day" />
          {data.days.map((day) => (
            <Card key={day.date}>
              <div className="flex items-start justify-between gap-4 flex-wrap">
                <div>
                  <div className="flex items-center gap-2 flex-wrap">
                    <span className="tv-heading text-ink-50">{dateLabel(day.date)}</span>
                    {day.closed ? <Chip tone="neutral">closed</Chip> : null}
                    {day.research ? <Chip tone="accent">research applied</Chip> : null}
                    {day.covers?.confidence ? <Chip tone="neutral">{day.covers.confidence} confidence</Chip> : null}
                  </div>
                  <p className="text-xs text-ink-400 mt-1">
                    {day.booked?.covers != null ? `${integer(day.booked.covers)} covers already booked` : ""}
                    {day.walkIns?.expected != null ? ` · ${integer(day.walkIns.expected)} walk-ins expected` : ""}
                    {day.turn?.minutes != null ? ` · ${minutes(day.turn.minutes)} turn (${day.turn.source ?? ""})` : ""}
                  </p>
                </div>
                <div className="text-right">
                  <span className="tv-metric text-ink-50">{integer(day.covers?.expected ?? null)}</span>
                  {day.covers?.low != null && day.covers?.high != null ? (
                    <p className="text-xs text-ink-400 mt-1">
                      {integer(day.covers.low)}–{integer(day.covers.high)} covers
                    </p>
                  ) : null}
                </div>
              </div>

              {day.sections.length ? (
                <div className="mt-4 flex flex-wrap gap-2">
                  {day.sections.map((section, index) => (
                    <span key={`${section.zone}-${index}`} className="rounded-md bg-panel-up px-2 py-1 text-xs text-ink-200">
                      {section.zone}: {integer(section.expectedCovers ?? null)}
                    </span>
                  ))}
                </div>
              ) : null}

              {day.factors?.used?.length ? (
                <ul className="mt-4 space-y-1">
                  {day.factors.used.map((factor, index) => (
                    <li key={index} className="text-xs text-ink-400">
                      <span className="text-ink-200">{factor.label}</span>
                      {factor.impactPct ? ` (${factor.impactPct > 0 ? "+" : ""}${factor.impactPct}%)` : ""} — {factor.detail}
                    </li>
                  ))}
                </ul>
              ) : null}

              {day.lastTableOut ? (
                <p className="text-xs text-ink-400 mt-3">Typical last table out: {day.lastTableOut}</p>
              ) : null}
            </Card>
          ))}
        </section>
      )}
    </div>
  );
}
